import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile,stat,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {verifyVideo} from '../src/utils/verifyVideo.js';
import {SceneSchema} from '../src/schemas/scene.js';
import {resolveWolfAsset} from '../src/assets/wolfAsset.js';
test('native wolf rendered artifacts, source integrity and evaluated animation evidence',async()=>{
  const job=process.env.WOLF_REVIEW_JOB;
  assert.ok(job,'Run npm run wolf:review first; set WOLF_REVIEW_JOB to its output directory');
  const report=JSON.parse(await readFile(path.join(job,'animation-report.json'),'utf8'));
  const plan=SceneSchema.parse(JSON.parse(await readFile(path.join(job,'plan.json'),'utf8')));
  assert.equal(report.status,'verified_pending_human_visual_review');
  assert.equal(report.autoRunEnabled,false);assert.equal(report.productionPublishingAllowed,false);
  assert.equal(report.nativeBoneCount,552);
  assert.deepEqual(report.actions.map((a:{nativeName:string})=>a.nativeName),['01-Idle(60)','02-Walk (42)']);
  assert.ok(report.actions.every((a:{evaluatedMotion:{rms:number}})=>a.evaluatedMotion.rms>.0001));
  assert.ok(report.idleWalkDifference.rms>.01 && report.savedSceneMotion.rms>.01);
  assert.ok(report.savedSceneMotion.maxPairDistanceChange>.001,'Mesh shape must change, not only move rigidly');
  assert.ok(report.driversAfterReopen.every((d:{type:string,simpleExpression:boolean,valid:boolean})=>d.valid && (d.type!=='SCRIPTED'||d.simpleExpression)));
  assert.ok(report.checks.all240FramesFramed && report.checks.all240FramesAboveFloor);
  assert.ok(report.placement.floorClearanceMin>0);
  assert.ok(report.drivers.every((d:{valid:boolean})=>d.valid));
  assert.equal((await readdir(path.join(job,'previews'))).filter(n=>n.endsWith('.png')).length,9);
  assert.ok((await stat(path.join(job,'scene.blend'))).size>0);
  await verifyVideo(path.join(job,'output/animation.mp4'),plan);
  const asset=await resolveWolfAsset();
  assert.equal(createHash('sha256').update(await readFile(asset.absolutePath)).digest('hex'),report.sourceSha256);
});
